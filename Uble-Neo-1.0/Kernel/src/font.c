/* ================================================================
 * GLYPH RENDERING
 * ================================================================ */
void draw_glyph(char c,uint32_t cell_x,uint32_t cell_y,uint8_t color) {
    if ((unsigned char)c == 0)
        c = ' ';
    else if ((unsigned char)c < 0x20 || (unsigned char)c > 0x7F)
        c = '?';
    uint8_t index = (uint8_t)c - 0x20;
    uint32_t fg = color_foreground(color);
    uint32_t bg = color_background(color);
    uint32_t px = cell_x * FONT_WIDTH;
    uint32_t py = cell_y * FONT_HEIGHT;
    for (uint32_t y = 0; y < FONT_HEIGHT; y++) {
        uint8_t bits = font8x8[index][y / 2];
        for (uint32_t x = 0; x < FONT_WIDTH; x++) {
            if (bits & (0x80 >> x))
                framebuffer_put_pixel(px + x, py + y, fg);
            else
                framebuffer_put_pixel(px + x, py + y, bg);
        }
    }
}